/**
 * Copy the OCR-level design tokens (@ocr/tokens, packages/tokens) into @ocr/ui.
 *
 * Write:  npx tsx scripts/sync-ocr-tokens.ts
 * Check:  npx tsx scripts/sync-ocr-tokens.ts --check   (exits 1 on drift, writes nothing)
 *
 * WHY A GENERATED COPY AND NOT AN IMPORT
 *   @ocr/tokens is the single source for the fleet's colors. But the spokes
 *   consume @ocr/ui on its own: ourWKRP's CI copies only packages/ui
 *   (scripts/ci-stage-ocr-workspace.sh) and OSE pins the hub by ref. A runtime
 *   import of ../../tokens would break both. So @ocr/ui carries a generated,
 *   checked-in copy, and this script's --check keeps it honest in the hub.
 *
 * WHAT IT COPIES
 *   - every color primitive the built-in brand roles reference (hex)
 *   - the role maps for each built-in brand and mode, as primitive names
 * Change colors in packages/tokens, then run this. Never edit the output by hand.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { primitives } from '../../tokens/src/primitive';
import { brands, SEMANTIC_ROLES } from '../../tokens/src/semantic';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '..', 'src', 'generated', 'ocr-tokens.ts');

const P = primitives as Record<string, string>;
const ref = (v: string): string => {
  const name = /^var\((--ocr-[\w-]+)\)$/.exec(v.trim())?.[1];
  if (name === undefined || !(name in P)) {
    throw new Error(`role value ${v} is not a primitive reference`);
  }
  return name;
};

const used = new Set<string>();
const roles: Record<string, Record<string, Record<string, string>>> = {};
for (const [brand, theme] of Object.entries(brands)) {
  const byMode: Record<string, Record<string, string>> = {};
  for (const mode of ['dark', 'light'] as const) {
    const map: Record<string, string> = {};
    for (const role of SEMANTIC_ROLES) {
      const name = ref(theme[mode][role]);
      used.add(name);
      map[role] = name;
    }
    byMode[mode] = map;
  }
  roles[brand] = byMode;
}

const prims = Object.fromEntries(
  [...used].sort().map((k) => {
    const hex = P[k];
    if (hex === undefined) throw new Error(`primitive ${k} has no value`);
    return [k, hex.toUpperCase()];
  }),
);

const obj = (o: unknown) => JSON.stringify(o, null, 2).replace(/"/g, "'");
const text = `// GENERATED by scripts/sync-ocr-tokens.ts from packages/tokens. Do not edit.
// Change colors in @ocr/tokens, then run: npx tsx scripts/sync-ocr-tokens.ts

/** Color primitives referenced by the OCR roles below (hex). */
export const ocrPrimitives = ${obj(prims)} as const;

export type OcrRole = ${SEMANTIC_ROLES.map((r) => `'${r}'`).join(' | ')};
export type OcrPrimitive = keyof typeof ocrPrimitives;

/** OCR role -> primitive name, per built-in brand and mode. */
export const ocrRoles: Record<string, Record<'dark' | 'light', Record<OcrRole, OcrPrimitive>>> = ${obj(roles)};
`;

if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== text) {
    console.error('✗ src/generated/ocr-tokens.ts is out of date with packages/tokens. Run: npx tsx scripts/sync-ocr-tokens.ts');
    process.exit(1);
  }
  console.log('✓ src/generated/ocr-tokens.ts matches packages/tokens');
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log(`@ocr/ui: wrote src/generated/ocr-tokens.ts (${used.size} primitives)`);
}
