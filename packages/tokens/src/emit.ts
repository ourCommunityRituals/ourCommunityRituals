/**
 * @ocr/tokens — emitters
 *
 * ONE source, TWO outputs: tokens.css for the browser and tokens.json for build
 * tooling (poster generation, docs, any Node script). They are generated from
 * the same objects in the same pass, so they cannot disagree — and
 * check-generated.mjs fails CI if dist/ is stale relative to src/.
 */

import { primitives } from './primitive.js';
import {
  brands,
  DEFAULT_BRAND,
  SEMANTIC_ROLES,
  BRAND_OVERRIDABLE,
  type RoleMap,
} from './semantic.js';
import { components } from './component.js';
import { surfaces, DEFAULT_SURFACE } from './surface.js';
import { uec } from './uec.js';

function decls(obj: Record<string, string>, indent = '  '): string {
  return Object.entries(obj)
    .map(([k, v]) => `${indent}${k}: ${v};`)
    .join('\n');
}

/**
 * Surface scaling. Multipliers are applied with calc() against the Tier 1 scale
 * rather than by enumerating sizes, so a new scale step upstream reaches every
 * surface automatically. A multiplier of 1 emits nothing — the baseline surface
 * costs zero bytes.
 */
function surfaceBlock(name: string): string {
  const s = surfaces[name];
  if (!s) return '';
  const lines: string[] = [];
  if (s.type !== 1) {
    for (const key of Object.keys(primitives).filter((k) => k.startsWith('--ocr-size-'))) {
      lines.push(`  ${key}: calc(${primitives[key as keyof typeof primitives]} * ${String(s.type)});`);
    }
  }
  if (s.space !== 1) {
    for (const key of Object.keys(primitives).filter((k) => k.startsWith('--ocr-space-'))) {
      lines.push(`  ${key}: calc(${primitives[key as keyof typeof primitives]} * ${String(s.space)});`);
    }
  }
  lines.push(`  --surface-target: ${s.target};`);
  const sel = name === DEFAULT_SURFACE ? ':root' : `[data-surface="${name}"]`;
  return `/* surface: ${name} — ${s.rationale} */\n${sel} {\n${lines.join('\n')}\n}`;
}

/**
 * A brand emits three blocks: dark as the base (the fleet's default ground),
 * then light under prefers-color-scheme, then light again under an explicit
 * [data-theme="light"] so a user override beats the OS in both directions.
 */
function brandBlock(name: string, dark: RoleMap, light: RoleMap): string {
  const base = name === DEFAULT_BRAND ? ':root' : `[data-brand="${name}"]`;
  const lightSel = name === DEFAULT_BRAND ? ':root' : `[data-brand="${name}"]`;
  return [
    `/* brand: ${name} — dark base */`,
    `${base} {`,
    decls(dark),
    '}',
    `@media (prefers-color-scheme: light) {`,
    `  ${lightSel}:not([data-theme="dark"]) {`,
    decls(light, '    '),
    '  }',
    '}',
    `${lightSel}[data-theme="light"] {`,
    decls(light),
    '}',
  ].join('\n');
}

/** The full stylesheet: primitives → semantics → components → surfaces → UEC. */
export function tokensCss(): string {
  const out: string[] = [
    '/* @ocr/tokens — GENERATED. Do not edit. Run `pnpm --filter @ocr/tokens build`. */',
    '',
    '/* ── Tier 1: primitives ───────────────────────────────────────────── */',
    ':root {',
    decls(primitives),
    '}',
    '',
    '/* ── Tier 2: semantics (paint axis — [data-brand]) ────────────────── */',
  ];

  for (const [name, theme] of Object.entries(brands)) {
    out.push(brandBlock(name, theme.dark, theme.light), '');
  }

  out.push(
    '/* ── Tier 3: components ───────────────────────────────────────────── */',
    ':root {',
    decls(components),
    '}',
    '',
    '/* ── Surface adaptation (scale axis — [data-surface]) ─────────────── */'
  );

  for (const name of Object.keys(surfaces)) {
    const block = surfaceBlock(name);
    if (block) out.push(block, '');
  }

  out.push(
    '/* ── UEC v1.1 — locked: theme-invariant AND brand-invariant ───────── */',
    ':root {',
    decls(uec),
    '}',
    ''
  );

  return out.join('\n');
}

/** The machine-readable mirror. Same values, same pass, structured by tier. */
export function tokensJson(): string {
  return (
    JSON.stringify(
      {
        $comment: 'GENERATED by @ocr/tokens. Do not edit. Run `pnpm --filter @ocr/tokens build`.',
        version: 1,
        primitive: primitives,
        semantic: {
          roles: SEMANTIC_ROLES,
          default: DEFAULT_BRAND,
          brands,
          /**
           * The variation surface, machine-enumerable. Tooling that offers
           * customization — the ourAirwaves client customizer above all — builds
           * its controls FROM this list rather than carrying its own copy. A
           * second hardcoded list is a second source of truth, and it drifts.
           */
          overridable: BRAND_OVERRIDABLE,
          /** Everything a brand may not touch, stated rather than implied. */
          locked: [
            ...SEMANTIC_ROLES.filter((r) => !BRAND_OVERRIDABLE.includes(r)),
            ...Object.keys(uec),
          ],
        },
        component: components,
        surface: { default: DEFAULT_SURFACE, scales: surfaces },
        uec,
      },
      null,
      2
    ) + '\n'
  );
}
